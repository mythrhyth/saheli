import type { AiAssistantProvider, AssistantContext, AssistantResponse } from "./ai.interface.js"
import { HeuristicAiProvider } from "./heuristic.provider.js"
import { env } from "../../config/env.js"

export class GeminiAiProvider implements AiAssistantProvider {
  private fallbackProvider = new HeuristicAiProvider()

  async generateResponse(prompt: string, context?: AssistantContext): Promise<AssistantResponse> {
    // If no Gemini API key is configured, safely use the verified heuristic fallback
    if (!env.GEMINI_API_KEY || env.AI_PROVIDER !== "gemini") {
      return this.fallbackProvider.generateResponse(prompt, context)
    }

    try {
      const response = await fetch(
        `https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key=${env.GEMINI_API_KEY}`,
        {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({
            contents: [
              {
                role: "user",
                parts: [
                  {
                    text: `You are Saheli's Women's Safety Assistant.
Guidelines:
1. Always prioritize immediate personal safety and de-escalation.
2. Recommend moving towards well-lit public places (open shops, pharmacies).
3. If immediate danger exists, always urge dialing 112 (India's Emergency Helpline) or 1091 (Women Helpline).
4. Never claim to have live GPS/surveillance information.
5. Provide concise, compassionate, actionable advice.

User Question: ${prompt}
Context: ${JSON.stringify(context || {})}`,
                  },
                ],
              },
            ],
          }),
        }
      )

      if (!response.ok) {
        console.warn(`Gemini API returned ${response.status}, falling back to heuristic.`)
        return this.fallbackProvider.generateResponse(prompt, context)
      }

      const data = (await response.json()) as {
        candidates?: Array<{ content?: { parts?: Array<{ text?: string }> } }>
      }

      const rawText = data.candidates?.[0]?.content?.parts?.[0]?.text
      if (!rawText) {
        return this.fallbackProvider.generateResponse(prompt, context)
      }

      return {
        text: rawText.trim(),
        sources: ["Google Gemini AI", "Saheli Safety Standards", "National Emergency Guidelines (112)"],
        provider: "gemini",
        isAiGenerated: true,
        disclaimer:
          "This answer was generated by Google Gemini AI. It does not replace real-time emergency services. Call 112 for urgent help.",
      }
    } catch (err) {
      console.error("Gemini API error, falling back to heuristic:", err)
      return this.fallbackProvider.generateResponse(prompt, context)
    }
  }
}
